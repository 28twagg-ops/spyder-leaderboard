import {cleanup,fireEvent,render,screen,within} from '@testing-library/react'
import {MemoryRouter} from 'react-router-dom'
import {afterEach,describe,expect,it} from 'vitest'
import App from '../App'
import {contraception} from '../data/contraception'
afterEach(()=>{cleanup();localStorage.clear()})
describe('preconception contraception navigation',()=>{
 it('removes podium methods, supports group exclusions and restores the lineup',async()=>{
  render(<MemoryRouter initialEntries={['/contraception']}><App/></MemoryRouter>)
  const panel=await screen.findByRole('region',{name:'Personal preference comparison'})
  const live=within(panel).getByRole('region',{name:'Live top three matches'})
  const group=within(panel).getByRole('group',{name:'Seven priority sliders'})
  for(const slider of within(group).getAllByRole('slider'))fireEvent.change(slider,{target:{value:'0'}})
  const eff=within(group).getByRole('slider',{name:'Effectiveness'})
  fireEvent.change(eff,{target:{value:'10'}})
  fireEvent.click(within(live).getByRole('button',{name:'Remove Arm implant from lineup'}))
  expect(within(live).queryByRole('link',{name:/Arm implant/})).not.toBeInTheDocument()
  expect(within(live).getByRole('link',{name:/Injection/})).toBeVisible()
  fireEvent.click(within(panel).getByRole('button',{name:/Filter out methods/}))
  fireEvent.click(within(panel).getByRole('button',{name:'Both IUDs'}))
  expect(within(live).queryByRole('link',{name:/Copper IUD/})).not.toBeInTheDocument()
  expect(within(live).queryByRole('link',{name:/LNG IUD/})).not.toBeInTheDocument()
  fireEvent.click(within(panel).getByRole('button',{name:'Restore Arm implant'}))
  expect(within(live).getByRole('link',{name:/Arm implant/})).toBeVisible()
  fireEvent.click(within(panel).getByRole('button',{name:'Restore all methods'}))
  expect(within(live).getByRole('link',{name:/Copper IUD/})).toBeVisible()
  expect(eff).toHaveValue('10')
  fireEvent.click(within(live).getByRole('button',{name:'Remove Copper IUD from lineup'}))
  fireEvent.click(within(panel).getByRole('button',{name:'Reset',exact:true}))
  const table=within(panel).getByRole('region',{name:'Scrollable live method ranking'})
  expect(within(table).getAllByRole('link')).toHaveLength(15)
  expect(within(panel).queryByRole('button',{name:'Restore all methods'})).not.toBeInTheDocument()
 })

 it('shows the sexual experience slider and adjustable annual supply scenario',async()=>{
  render(<MemoryRouter initialEntries={['/contraception']}><App/></MemoryRouter>)
  const panel=await screen.findByRole('region',{name:'Personal preference comparison'})
  expect(within(panel).getByRole('slider',{name:'Sexual feel & spontaneity'})).toHaveAttribute('max','10')
  fireEvent.click(within(panel).getByText('Cost scenario · 21 acts/month'))
  const input=within(panel).getByLabelText('Sex acts per month')
  expect(input).toHaveValue(21)
  expect(within(panel).getByText('252 acts/year · 756 over three years.',{exact:false})).toBeInTheDocument()
  fireEvent.change(input,{target:{value:'10'}})
  expect(within(panel).getByText('120 acts/year · 360 over three years.',{exact:false})).toBeInTheDocument()
 })

 it('shows tie-inclusive results and lets users choose an actual delivery format',async()=>{
  render(<MemoryRouter initialEntries={['/contraception']}><App/></MemoryRouter>)
  const panel=await screen.findByRole('region',{name:'Personal preference comparison'})
  fireEvent.click(within(panel).getByRole('button',{name:/Preferred form: Any/}))
  fireEvent.change(within(panel).getByRole('combobox',{name:'Preferred delivery format'}),{target:{value:'gel'}})
  const live=within(panel).getByRole('region',{name:'Live top three matches'})
  expect(within(live).getAllByRole('link')).toHaveLength(1)
  expect(within(live).getByRole('link',{name:/Spermicide \/ pH regulator/})).toBeVisible()
  fireEvent.change(within(panel).getByRole('combobox',{name:'Preferred delivery format'}),{target:{value:'all'}})
  const group=within(panel).getByRole('group',{name:'Seven priority sliders'})
  for(const slider of within(group).getAllByRole('slider'))fireEvent.change(slider,{target:{value:'0'}})
  fireEvent.change(within(group).getByRole('slider',{name:'Future fertility'}),{target:{value:'10'}})
  expect(within(live).getAllByRole('link')).toHaveLength(14)
  expect(within(live).getByText(/All methods sharing a podium rank/)).toBeVisible()
 })
 it('keeps all methods in the live table and opens individual product links',async()=>{
  render(<MemoryRouter initialEntries={['/contraception']}><App/></MemoryRouter>)
  const list=await screen.findByRole('region',{name:'All live method matches'})
  const table=within(list).getByRole('region',{name:'Scrollable live method ranking'})
  expect(within(table).getAllByRole('link')).toHaveLength(15)
  fireEvent.click(within(table).getByRole('button',{name:'Show products for Progestin-only pill'}))
  expect(within(table).getByRole('link',{name:/Slynd/})).toHaveAttribute('href','/contraception/product-slynd')
  expect(within(table).getByRole('link',{name:/Opill/})).toBeVisible()
  fireEvent.click(within(table).getByRole('button',{name:'Show products for Spermicide / pH regulator'}))
  expect(within(table).getByRole('link',{name:/Phexxi/})).toBeVisible()
  const group=screen.getByRole('group',{name:'Seven priority sliders'})
  fireEvent.change(within(group).getByRole('slider',{name:'Comfort & periods'}),{target:{value:'10'}})
  expect(within(table).getByRole('link',{name:/Copper IUD/})).toBeVisible()
  expect(within(table).getAllByText('Excluded').length).toBeGreaterThan(0)
 })
 it('applies the essential comfort filter even when all seven priorities are high',async()=>{
  render(<MemoryRouter initialEntries={['/contraception']}><App/></MemoryRouter>)
  const group=await screen.findByRole('group',{name:'Seven priority sliders'})
  for(const s of within(group).getAllByRole('slider'))fireEvent.change(s,{target:{value:'10'}})
  expect(screen.getByText(/Comfort essential: excludes IUDs/)).toBeVisible()
  const live=screen.getByRole('region',{name:'Live top three matches'})
  expect(within(live).getAllByRole('link').every(l=>!/IUD|implant|injection/i.test(l.textContent||''))).toBe(true)
 })
 it('provides exact product links only when a specific listing was identified',async()=>{
  render(<MemoryRouter initialEntries={['/contraception/product-opill']}><App/></MemoryRouter>)
  expect(await screen.findByRole('link',{name:/Amazon · Opill 84 count/})).toHaveAttribute('href','https://www.amazon.com/dp/B0CJYHQ3CB')
  expect(contraception.products.every(p=>!p.retail||p.retail.sourceIds.every(id=>contraception.sources.some(s=>s.id===id)))).toBe(true)
 })
 it('opens product library, filters formulations and reaches evidence and funding',async()=>{
  render(<MemoryRouter initialEntries={['/contraception']}><App/></MemoryRouter>)
  fireEvent.click(await screen.findByRole('link',{name:/Explore specific brands & formulations/}))
  expect(await screen.findByRole('heading',{name:'Brands & formulations'})).toBeVisible()
  fireEvent.change(screen.getByLabelText('Search name or ingredient'),{target:{value:'Slynd'}})
  fireEvent.click(screen.getByRole('link',{name:/Slynd.*Drospirenone/}))
  expect(await screen.findByRole('heading',{name:'Slynd',level:1})).toBeVisible()
  expect(screen.getByRole('heading',{name:'What studies found'})).toBeVisible()
  expect(screen.getByText(/Studies, funding & limitations/)).toBeInTheDocument()
 })
 it('lists three US progestin-only formulations in the method profile',async()=>{
  render(<MemoryRouter initialEntries={['/contraception/method-mini-pill']}><App/></MemoryRouter>)
  const region=await screen.findByRole('region',{name:'Product research'})
  expect(within(region).getByRole('link',{name:/Opill/})).toBeVisible()
  expect(within(region).getByRole('link',{name:/Slynd/})).toBeVisible()
  expect(within(region).getByRole('link',{name:/Norethindrone mini-pill/})).toBeVisible()
 })
 it('retains unique product links with traceable source records',()=>{
  const ids=new Set(contraception.sources.map(s=>s.id))
  expect(new Set(contraception.products.map(p=>p.id)).size).toBe(contraception.products.length)
  expect(contraception.products.every(p=>p.sourceIds.length>0&&p.sourceIds.every(id=>ids.has(id))&&contraception.sections.some(s=>s.id===p.id))).toBe(true)
 })
 it('shows seven compact sliders and live matches directly on the landing page',async()=>{
  render(<MemoryRouter initialEntries={['/contraception']}><App/></MemoryRouter>)
  const panel=await screen.findByRole('region',{name:'Personal preference comparison'})
  const live=within(panel).getByRole('region',{name:'Live top three matches'})
  expect(within(live).getByRole('heading',{name:'Your top three matches'})).toBeVisible()
  const group=within(panel).getByRole('group',{name:'Seven priority sliders'})
  const sliders=within(group).getAllByRole('slider')
  expect(sliders).toHaveLength(7)
  expect(sliders.every(s=>s.getAttribute('max')==='10')).toBe(true)
  for(const slider of sliders)fireEvent.change(slider,{target:{value:'0'}})
  fireEvent.change(within(group).getByRole('slider',{name:'Hormone exposure'}),{target:{value:'10'}})
  fireEvent.change(within(group).getByRole('slider',{name:'Effectiveness'}),{target:{value:'10'}})
  expect(within(live).getAllByRole('link').length).toBeGreaterThanOrEqual(3)
  expect(within(live).getAllByRole('link')[0]).toHaveTextContent('Copper IUD')
  fireEvent.change(within(group).getByRole('slider',{name:'Effectiveness'}),{target:{value:'0'}})
  fireEvent.change(within(group).getByRole('slider',{name:'Comfort & periods'}),{target:{value:'10'}})
  expect(within(live).queryByRole('link',{name:/Copper IUD/})).not.toBeInTheDocument()
  expect(within(group).getByRole('slider',{name:'Total 3-year cost'})).toBeVisible()
 })
 it('puts all research graphs on the overview with compact method navigation',async()=>{
  render(<MemoryRouter initialEntries={['/timeline/preconception']}><App/></MemoryRouter>)
  fireEvent.click(screen.getByRole('link',{name:/Birth control & preparing for pregnancy/}))
  expect(await screen.findByRole('heading',{name:'Birth control & family planning'})).toBeVisible()
  const research=screen.getByRole('region',{name:'Research comparisons'})
  expect(within(research).getByRole('region',{name:'Pregnancy prevention in everyday use'})).toBeVisible()
  for(const p of contraception.evidencePanels)expect(within(research).getByRole('region',{name:p.title})).toBeVisible()
  const directory=screen.getByRole('region',{name:'Explore individual methods'})
  expect(within(directory).getAllByRole('link')).toHaveLength(8)
  fireEvent.click(within(directory).getByRole('button',{name:/Show all 15 methods/}))
  expect(within(directory).getAllByRole('link')).toHaveLength(15)
  fireEvent.click(within(directory).getByRole('button',{name:'No hormones'}))
  expect(within(directory).getByRole('link',{name:'Explore Copper IUD'})).toBeVisible()
  expect(within(directory).queryByRole('link',{name:'Explore LNG IUD'})).not.toBeInTheDocument()
  fireEvent.click(within(directory).getByRole('link',{name:'Explore Copper IUD'}))
  expect(await screen.findByRole('heading',{name:'Copper IUD',level:1})).toBeVisible()
  expect(screen.getByRole('heading',{name:'Cost & comfort'})).toBeVisible()
  expect(screen.getByText('$0–$1,800')).toBeVisible()
  expect(screen.getByRole('heading',{name:'Advantages'})).toBeVisible()
  expect(screen.getByRole('heading',{name:'Trade-offs'})).toBeVisible()
  fireEvent.click(screen.getByRole('button',{name:'Back'}))
  expect(await screen.findByRole('heading',{name:'Birth control & family planning'})).toBeVisible()
 })
 it('keeps the existing priority guide and pain evidence routes',async()=>{
  render(<MemoryRouter initialEntries={['/contraception/decision-guide']}><App/></MemoryRouter>)
  expect(await screen.findByRole('heading',{name:'Decision guide: compare your priorities'})).toBeVisible()
  const guide=screen.getByRole('region',{name:'Compare priorities'})
  expect(within(guide).getByRole('link',{name:/1\. Copper IUD/})).toBeVisible()
  fireEvent.change(within(guide).getByLabelText('What matters in the comparison?'),{target:{value:'long-term'}})
  expect(within(guide).getByRole('link',{name:'Mood and depression'})).toBeVisible()
  fireEvent.click(within(guide).getByRole('link',{name:'Placement pain and pain control'}))
  expect(await screen.findByRole('region',{name:'IUD insertion pain: 2018 randomized trial'})).toBeVisible()
  expect(screen.getByText('33/100 (3.3/10 equivalent)')).toBeVisible()
 })
 it('filters the existing comparison route',async()=>{
  render(<MemoryRouter initialEntries={['/contraception/compare']}><App/></MemoryRouter>)
  expect(await screen.findByRole('heading',{name:'Compare birth control methods'})).toBeVisible()
  fireEvent.change(screen.getByLabelText('Filter by hormone exposure'),{target:{value:'none'}})
  expect(screen.getByRole('link',{name:/Copper IUD\s*0\.8%/})).toBeVisible()
  expect(screen.queryByRole('link',{name:/LNG IUD\s*0\.1–0\.4%/})).not.toBeInTheDocument()
 })
 it('finds the copper IUD in Search and goes back to the original query',async()=>{
  render(<MemoryRouter initialEntries={['/library']}><App/></MemoryRouter>)
  fireEvent.change(screen.getByLabelText('Search articles'),{target:{value:'copper iud'}})
  fireEvent.click(within(screen.getByRole('region',{name:'Birth control results'})).getByRole('link',{name:/Copper IUD: no added hormones/}))
  expect(await screen.findByRole('heading',{name:'Copper IUD: no added hormones'})).toBeVisible()
  fireEvent.click(screen.getByRole('button',{name:'Back'}))
  expect(await screen.findByLabelText('Search articles')).toHaveValue('copper iud')
 })
})
